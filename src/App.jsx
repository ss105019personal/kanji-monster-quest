class ErrorBoundary extends React.Component {
  constructor(props) {
    super(props);
    this.state = { hasError: false, message: "" };
  }
  static getDerivedStateFromError(error) {
    return { hasError: true, message: (error && error.message) || "" };
  }
  componentDidCatch(error, info) {
    console.error("App crashed:", error, info);
  }
  render() {
    if (this.state.hasError) {
      return (
        <div style={styles.app}>
          <GlobalStyle />
          <div style={styles.profileScreen}>
            <div style={{ fontSize: 40 }}>😵</div>
            <div style={styles.wildLabel}>エラーが おきちゃいました…</div>
            <div style={{ fontSize: 11, opacity: 0.6, wordBreak: "break-all", maxWidth: 280 }}>{this.state.message}</div>
            <button
              style={styles.nextBtn}
              onClick={() => {
                this.setState({ hasError: false, message: "" });
              }}
            >
              🔄 もういちど ためす
            </button>
            <div style={{ fontSize: 10, opacity: 0.5, maxWidth: 280 }}>
              なおらない ときは ページを さいよみこみ してみてね
            </div>
          </div>
        </div>
      );
    }
    return this.props.children;
  }
}

export default function App() {
  return (
    <ErrorBoundary>
      <AppInner />
    </ErrorBoundary>
  );
}
