function WritingPad({ char, size = 200, showAnswer = false }) {
  const canvasRef = useRef(null);
  const drawingRef = useRef(false);
  const lastPos = useRef({ x: 0, y: 0 });

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext("2d");
    ctx.lineWidth = 7;
    ctx.lineCap = "round";
    ctx.lineJoin = "round";
    ctx.strokeStyle = "#2b2740";

    function getPos(e) {
      const rect = canvas.getBoundingClientRect();
      return {
        x: (e.clientX - rect.left) * (canvas.width / rect.width),
        y: (e.clientY - rect.top) * (canvas.height / rect.height),
      };
    }
    function start(e) {
      e.preventDefault();
      drawingRef.current = true;
      lastPos.current = getPos(e);
    }
    function move(e) {
      if (!drawingRef.current) return;
      e.preventDefault();
      const pos = getPos(e);
      ctx.beginPath();
      ctx.moveTo(lastPos.current.x, lastPos.current.y);
      ctx.lineTo(pos.x, pos.y);
      ctx.stroke();
      lastPos.current = pos;
    }
    function end() {
      drawingRef.current = false;
    }

    canvas.addEventListener("pointerdown", start);
    canvas.addEventListener("pointermove", move);
    window.addEventListener("pointerup", end);
    return () => {
      canvas.removeEventListener("pointerdown", start);
      canvas.removeEventListener("pointermove", move);
      window.removeEventListener("pointerup", end);
    };
  }, []);

  function clearPad() {
    const canvas = canvasRef.current;
    const ctx = canvas.getContext("2d");
    ctx.clearRect(0, 0, canvas.width, canvas.height);
  }

  return (
    <div>
      <div style={{ position: "relative", width: size, height: size, margin: "0 auto" }}>
        <svg width={size} height={size} style={{ position: "absolute", inset: 0, borderRadius: 14 }}>
          <rect x="1" y="1" width={size - 2} height={size - 2} fill="#fdf9ee" stroke="#c9bfa0" strokeWidth="2" rx="14" />
          <line x1={size / 2} y1="8" x2={size / 2} y2={size - 8} stroke="#e4dcc4" strokeWidth="1.5" strokeDasharray="5 5" />
          <line x1="8" y1={size / 2} x2={size - 8} y2={size / 2} stroke="#e4dcc4" strokeWidth="1.5" strokeDasharray="5 5" />
        </svg>
        {showAnswer && (
          <div
            style={{
              position: "absolute",
              inset: 0,
              display: "flex",
              alignItems: "center",
              justifyContent: "center",
              fontSize: size * 0.58,
              color: "#c0392b33",
              fontFamily: "'Klee One', 'Zen Maru Gothic', sans-serif",
              fontWeight: 900,
              pointerEvents: "none",
            }}
          >
            {char}
          </div>
        )}
        <canvas
          ref={canvasRef}
          width={size}
          height={size}
          style={{ position: "absolute", inset: 0, touchAction: "none", borderRadius: 14 }}
        />
      </div>
      <div style={{ display: "flex", justifyContent: "center", gap: 8, marginTop: 10 }}>
        <button onClick={clearPad} style={styles.miniBtn}>
          🧹 けす
        </button>
      </div>
    </div>
  );
}

