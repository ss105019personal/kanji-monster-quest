function parseGrade(raw) {
  return raw
    .trim()
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      const [char, on, kun, meaning, example, exampleReading, type] = line.split("|");
      return {
        char,
        on: on ? on.split(",") : [],
        kun: kun ? kun.split(",") : [],
        meaning,
        example,
        exampleReading,
        type,
      };
    });
}

