// 「しずか」「たしか」のような「〜か」の な形容詞は めいしと まぎらわしい ため こべつに してい
const OKURI_FORCE_1CHAR = new Map([
  ["しずか", "か"],
  ["たしか", "か"],
  ["ゆたか", "か"],
  ["おごそか", "か"],
]);
// 「まつ」のように おなじ よみでも かんじによって おくりがなが ちがう もの（さいゆうせん で かくにん）
const OKURI_CHAR_OVERRIDES = new Map([
  ["松:まつ", ""], // 松＝まつ（めいし、おくりがな なし）
  ["待:まつ", "つ"], // 待つ＝ま＋つ（どうし）
]);
function splitOkurigana(reading, char) {
  if (!reading || isKatakanaOnly(reading) || reading.length < 2) return { stem: reading || "", okuri: "" };
  if (char && OKURI_CHAR_OVERRIDES.has(`${char}:${reading}`)) {
    const okuri = OKURI_CHAR_OVERRIDES.get(`${char}:${reading}`);
    return okuri ? { stem: reading.slice(0, -okuri.length), okuri } : { stem: reading, okuri: "" };
  }
  if (OKURI_NO_SPLIT_EXCEPTIONS.has(reading)) return { stem: reading, okuri: "" };
  if (OKURI_FORCE.has(reading)) {
    const okuri = OKURI_FORCE.get(reading);
    return { stem: reading.slice(0, -okuri.length), okuri };
  }
  if (OKURI_FORCE_1CHAR.has(reading)) {
    const okuri = OKURI_FORCE_1CHAR.get(reading);
    return { stem: reading.slice(0, -okuri.length), okuri };
  }
  if (reading.endsWith("しい")) return { stem: reading.slice(0, -2), okuri: "しい" };
  if (reading.endsWith("きい")) return { stem: reading.slice(0, -2), okuri: "きい" };
  for (const end of OKURI_2CHAR_ENDINGS) {
    if (reading.length > 2 && reading.endsWith(end)) {
      return { stem: reading.slice(0, -2), okuri: end };
    }
  }
  const last = reading[reading.length - 1];
  if (OKURI_1CHAR_ENDINGS.includes(last)) {
    return { stem: reading.slice(0, -1), okuri: last };
  }
  return { stem: reading, okuri: "" };
}
function ReadingChoiceText({ text, char }) {
  const { stem, okuri } = splitOkurigana(text, char);
  if (!okuri) return <>{text}</>;
  return (
    <>
      {stem}
      <span style={{ color: "#ffd37a" }}>({okuri})</span>
    </>
  );
}
function formatKunReading(reading, char) {
  const { stem, okuri } = splitOkurigana(reading, char);
  return okuri ? `${stem}(${okuri})` : reading;
}

function blankedExample(entry, char) {
  const idx = entry.example.indexOf(char);
  if (idx === -1) {
    return { before: "", after: entry.example, found: false };
  }
  return {
    before: entry.example.slice(0, idx),
    after: entry.example.slice(idx + 1),
    found: true,
  };
}

