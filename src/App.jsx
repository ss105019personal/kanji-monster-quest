function makeBossQuestion(g) {
  const chars = g.chars;
  const char = chars[Math.floor(Math.random() * chars.length)];
  const entry = KANJI_DB[char];
  const mode = Math.random() < 0.5 ? "reading" : "meaning";
  let correct, distractorPool;
  if (mode === "reading") {
    correct = entry.kun.length ? entry.kun[0] : entry.on[0];
    distractorPool = chars.filter((c) => c !== char).flatMap((c) => [...KANJI_DB[c].kun, ...KANJI_DB[c].on]);
  } else {
    correct = entry.meaning;
    distractorPool = chars.filter((c) => c !== char).map((c) => KANJI_DB[c].meaning);
  }
  const distractors = shuffle([...new Set(distractorPool)]).slice(0, 3);
  const choices = shuffle([correct, ...distractors]);
  return { char, entry, mode, choices, correctIdx: choices.indexOf(correct) };
}

function MonsterCreature({ char, clearedCount = 0, level = 1, size = 140, pop = false }) {
  const meta = TYPE_META[(KANJI_DB[char] || {}).type] || TYPE_META.spirit;
  const captured = clearedCount >= 3;
  const t = clearedCount / 3;
  const awake = clearedCount > 0;
  const revealChar = clearedCount > 0;
  const path = bodyPathFor(char);
  const archetype = archetypeFor(char);
  const gradId = `grad-${char}-${clearedCount}`;
  const growth = captured ? 1 + (level - 1) * 0.035 : 1;

  const bodyLight = lerpColor("#8a8a94", meta.grad[0], t);
  const bodyDark = lerpColor("#54545e", meta.grad[1], t);
  const featureColor = lerpColor("#6a6a74", meta.accent, t);

  const props = {
    fillUrl: `url(#${gradId})`,
    bodyDark,
    featureColor,
    awake,
    char,
    revealChar,
    path,
  };

  let Body;
  switch (archetype) {
    case "slime":
      Body = SlimeBody;
      break;
    case "knight":
      Body = KnightBody;
      break;
    case "horse":
      Body = HorseBody;
      break;
    case "tiger":
      Body = TigerBody;
      break;
    case "water":
      Body = WaterBody;
      break;
    case "golem":
      Body = GolemBody;
      break;
    default:
      Body = DragonBody;
  }

  return (
    <svg
      viewBox="0 0 120 120"
      width={size}
      height={size}
      className={pop ? "monster-pop" : ""}
      style={{ overflow: "visible", transform: `scale(${growth})` }}
    >
      <defs>
        <linearGradient id={gradId} x1="0" y1="0" x2="1" y2="1">
          <stop offset="0%" stopColor={bodyLight} />
          <stop offset="55%" stopColor={bodyLight} />
          <stop offset="100%" stopColor={bodyDark} />
        </linearGradient>
      </defs>

      <Body {...props} />

      {captured && level >= 4 && (
        <>
          <circle cx="14" cy="28" r="2.5" fill={meta.accent} opacity="0.9" />
          <circle cx="106" cy="28" r="2.5" fill={meta.accent} opacity="0.9" />
        </>
      )}
      {captured && <TypeAccessory type={(KANJI_DB[char] || {}).type} accent={meta.accent} />}
    </svg>
  );
}

